import type { ExtensionAPI } from '@earendil-works/pi-coding-agent';
import { getAgentDir, loadProjectContextFiles } from '@earendil-works/pi-coding-agent';
import { homedir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { hasRules, rebuildAgents, rememberRule, selectProjectContext } from '../../../core/project-context.mjs';

export function installProjectContext(pi: ExtensionAPI) {
  let snapshot: Array<{ path: string; content: string }> | undefined;
  pi.on('session_start', async (_event, ctx) => {
    // Disk can change later; this array must not. Pi exposes contextFiles in 1.5.2.
    rebuildAgents(ctx.cwd);
    snapshot = selectProjectContext(loadProjectContextFiles({ cwd: ctx.cwd, agentDir: getAgentDir() }), ctx.cwd, getAgentDir());
  });
  pi.on('before_agent_start', async (event) => {
    if (snapshot && event.systemPromptOptions) event.systemPromptOptions.contextFiles = snapshot.map(file => ({ ...file }));
  });
  pi.on('tool_result', async (event, ctx) => {
    if (event.isError || !['edit', 'write'].includes(event.toolName)) return;
    const input = event.input as { path?: string };
    if (!input?.path) return;
    const file = resolve(ctx.cwd, input.path);
    if (['rules.md', 'header.md'].some(name => file === join(dirname(dirname(file)), '.agent', name))) {
      rebuildAgents(dirname(dirname(file)));
    }
  });
  pi.registerCommand('rules', {
    description: 'Agent: /rules init separa regras e cabeçalho do AGENTS.md',
    handler: async (args, ctx) => {
      if (args.trim() !== 'init') return ctx.ui.notify('Use /rules init.', 'info');
      // Prompt em inglês só para o modelo; o TUI mostra o aviso em português.
      pi.sendMessage({ customType: 'agent-rules-init', display: false, content: [
        'Migrate this project context to the Agent sources.',
        'Read AGENTS.md and .agent/workflow.md if they exist. Keep every rule in .agent/rules.md; split a short header into .agent/header.md.',
        'Do not include the personal AGENTS.md. Fold workflow.md into rules.md and remove the legacy file after keeping its content.',
        'Replace the manual AGENTS.md explicitly, only as part of this requested migration.',
        '<!-- generated by agent from .agent/header.md + .agent/rules.md — edit those -->',
        'Put that marker on the first line of AGENTS.md, then header + rules and relative pointers to .agent/notes.md, STATUS.md, HISTORY.md and docs when they exist.',
        'The Agent rebuilds the file on disk when the sources change; this session context stays fixed until the next session.',
      ].join('\n') }, { triggerTurn: true, deliverAs: 'followUp' });
      ctx.ui.notify('Pedido enviado ao agente: migrar AGENTS.md para .agent/rules.md e .agent/header.md.', 'info');
    },
  });
  pi.registerCommand('remember', {
    description: 'Agent: salvar uma regra pessoal ou do projeto',
    handler: async (args, ctx) => {
      const text = args.trim();
      if (!text) return ctx.ui.notify('Use /remember <texto>.', 'error');
      const personal = join(homedir(), '.agent/AGENTS.md');
      const project = join(ctx.cwd, '.agent/rules.md');
      let file: string | undefined;
      if (ctx.hasUI) file = await ctx.ui.select('Salvar regra em:', [personal, project]);
      else if (hasRules(ctx.cwd)) file = project;
      else return ctx.ui.notify('Sem UI: crie .agent/rules.md com /rules init antes de usar /remember.', 'error');
      if (!file) return;
      try {
        rememberRule(file, text, ctx.cwd);
        ctx.ui.notify(`Regra salva em ${file}. Contexto atualizado na próxima sessão.`, 'info');
      } catch (error) { ctx.ui.notify(`Não foi possível salvar regra: ${String(error)}`, 'error'); }
    },
  });
}
