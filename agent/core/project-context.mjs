// Shared disk format and context selection for the host and children. No Pi patch.
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

export const GENERATED_MARKER = '<!-- generated by agent from .agent/header.md + .agent/rules.md — edit those -->';
export const isGenerated = text => text.startsWith(`${GENERATED_MARKER}\n`);
const read = file => existsSync(file) ? readFileSync(file, 'utf8') : '';
export const hasRules = cwd => existsSync(join(cwd, '.agent/rules.md'));

export function contextPointers(cwd) {
  return ['.agent/notes.md', 'STATUS.md', 'HISTORY.md', 'docs']
    .filter(file => existsSync(join(cwd, file)))
    .map(file => `Read ${join(cwd, file)} when needed.`).join('\n');
}

export function renderAgents(cwd) {
  // Relative pointers keep the generated file portable across checkouts.
  const pointers = ['.agent/notes.md', 'STATUS.md', 'HISTORY.md', 'docs']
    .filter(file => existsSync(join(cwd, file)))
    .map(file => `- Read ${file} when needed.`).join('\n');
  return [GENERATED_MARKER, read(join(cwd, '.agent/header.md')).trim(),
    read(join(cwd, '.agent/rules.md')).trim(), pointers].filter(Boolean).join('\n\n') + '\n';
}

export function rebuildAgents(cwd) {
  const file = join(cwd, 'AGENTS.md');
  if (existsSync(file) && !isGenerated(read(file))) return false;
  if (!hasRules(cwd)) return false;
  const output = renderAgents(cwd);
  if (read(file) === output) return false;
  writeFileSync(file, output);
  return true;
}

export function sourceContext(cwd) {
  return ['rules.md', 'header.md'].map(file => ({ path: join(cwd, '.agent', file), content: read(join(cwd, '.agent', file)) }))
    .filter(file => existsSync(file.path));
}

/** Preserve Pi discovery/shadowing and personal context. Sources without AGENTS.md work at cwd too. */
export function selectProjectContext(files, cwd, agentDir) {
  const out = [];
  let covered = false;
  for (const file of files) {
    const dir = dirname(file.path);
    if (resolve(dir) === resolve(agentDir)) { out.push({ ...file }); continue; }
    if (resolve(dir) === resolve(cwd)) covered = true;
    if (basename(file.path) === 'AGENTS.md' && isGenerated(file.content)) {
      out.push(...sourceContext(dir), { path: file.path,
        content: [`Read the complete AGENTS.md at ${file.path} when needed.`, contextPointers(dir)].filter(Boolean).join('\n') });
    } else {
      out.push({ ...file, content: `${file.content}${basename(file.path) === 'AGENTS.md' ? '\nUse /rules init to split project rules and header into .agent sources.' : ''}` });
    }
  }
  if (!covered && hasRules(cwd)) {
    out.push(...sourceContext(cwd), { path: join(cwd, 'AGENTS.md'), content: [
      `Read the complete AGENTS.md at ${join(cwd, 'AGENTS.md')} when needed.`, contextPointers(cwd),
    ].filter(Boolean).join('\n') });
  }
  return out;
}

export function rememberRule(file, text, cwd) {
  mkdirSync(dirname(file), { recursive: true });
  const current = read(file);
  appendFileSync(file, `${current && !current.endsWith('\n') ? '\n' : ''}- ${text.trim()}\n`);
  rebuildAgents(cwd);
}
